//! Extracts just `(name, version)` pairs out of the two lockfile
//! formats this tool understands. Everything else in either file
//! (checksums, sources, dependency edges, `resolved` URLs) is
//! irrelevant to "what package versions changed" and deliberately
//! dropped rather than modeled.

use serde_json::Value as JsonValue;
use toml::Value as TomlValue;

/// One resolved package at one version. A single `name` can legitimately
/// appear more than once — both lockfile formats allow the same crate/
/// package to be resolved at multiple semver-incompatible versions at
/// once — so this is intentionally not a map keyed by name.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Package {
    pub name: String,
    pub version: String,
}

/// `Cargo.lock`'s `[[package]]` entries.
pub fn parse_cargo_lock(content: &str) -> Result<Vec<Package>, String> {
    let parsed: TomlValue = content
        .parse()
        .map_err(|e| format!("not valid TOML: {e}"))?;
    let packages = parsed
        .get("package")
        .and_then(TomlValue::as_array)
        .ok_or_else(|| "no [[package]] entries found — is this really a Cargo.lock?".to_string())?;

    Ok(packages
        .iter()
        .filter_map(|p| {
            let name = p.get("name")?.as_str()?.to_string();
            let version = p.get("version")?.as_str()?.to_string();
            Some(Package { name, version })
        })
        .collect())
}

/// `package-lock.json`'s modern (`lockfileVersion` 2/3) `"packages"`
/// map: `node_modules/<name>` (or a nested
/// `node_modules/a/node_modules/b` path for a transitively deduped
/// package) -> `{"version": "..."}`. The root `""` entry describes the
/// project itself, not a dependency, and is skipped. Older
/// `lockfileVersion` 1's nested `"dependencies"` tree is not parsed —
/// see README.
pub fn parse_npm_lock(content: &str) -> Result<Vec<Package>, String> {
    let parsed: JsonValue =
        serde_json::from_str(content).map_err(|e| format!("not valid JSON: {e}"))?;
    let packages = parsed
        .get("packages")
        .and_then(JsonValue::as_object)
        .ok_or_else(|| {
            "no \"packages\" object — is this a lockfileVersion 2/3 package-lock.json?".to_string()
        })?;

    Ok(packages
        .iter()
        .filter_map(|(path, entry)| {
            if path.is_empty() {
                return None; // the project itself, not a dependency
            }
            let name = path
                .rsplit_once("node_modules/")
                .map(|(_, rest)| rest)
                .unwrap_or(path)
                .trim_end_matches('/')
                .to_string();
            let version = entry.get("version")?.as_str()?.to_string();
            Some(Package { name, version })
        })
        .collect())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_a_realistic_cargo_lock() {
        let content = r#"
# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 3

[[package]]
name = "anyhow"
version = "1.0.75"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "aaaa"

[[package]]
name = "serde"
version = "1.0.190"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "bbbb"
"#;
        let packages = parse_cargo_lock(content).unwrap();
        assert_eq!(packages.len(), 2);
        assert!(packages.contains(&Package {
            name: "anyhow".to_string(),
            version: "1.0.75".to_string()
        }));
        assert!(packages.contains(&Package {
            name: "serde".to_string(),
            version: "1.0.190".to_string()
        }));
    }

    #[test]
    fn cargo_lock_allows_the_same_crate_at_two_versions() {
        let content = r#"
[[package]]
name = "syn"
version = "1.0.109"

[[package]]
name = "syn"
version = "2.0.38"
"#;
        let packages = parse_cargo_lock(content).unwrap();
        assert_eq!(packages.len(), 2);
        assert_eq!(packages.iter().filter(|p| p.name == "syn").count(), 2);
    }

    #[test]
    fn malformed_cargo_lock_is_a_clean_error() {
        assert!(parse_cargo_lock("not toml at all {{{").is_err());
    }

    #[test]
    fn cargo_lock_missing_package_array_is_a_clean_error() {
        assert!(parse_cargo_lock("version = 3\n").is_err());
    }

    #[test]
    fn parses_a_realistic_npm_lock() {
        let content = r#"{
  "name": "myapp",
  "lockfileVersion": 3,
  "packages": {
    "": { "name": "myapp", "version": "1.0.0" },
    "node_modules/lodash": { "version": "4.17.21" },
    "node_modules/express": { "version": "4.18.2" }
  }
}"#;
        let packages = parse_npm_lock(content).unwrap();
        assert_eq!(packages.len(), 2);
        assert!(packages.contains(&Package {
            name: "lodash".to_string(),
            version: "4.17.21".to_string()
        }));
    }

    #[test]
    fn npm_lock_handles_a_nested_scoped_transitive_dependency() {
        let content = r#"{
  "packages": {
    "": {},
    "node_modules/foo/node_modules/@scope/bar": { "version": "2.0.0" }
  }
}"#;
        let packages = parse_npm_lock(content).unwrap();
        assert_eq!(packages.len(), 1);
        assert_eq!(packages[0].name, "@scope/bar");
        assert_eq!(packages[0].version, "2.0.0");
    }

    #[test]
    fn npm_lock_missing_packages_object_is_a_clean_error() {
        assert!(parse_npm_lock(r#"{"lockfileVersion": 1}"#).is_err());
    }

    #[test]
    fn malformed_npm_lock_is_a_clean_error() {
        assert!(parse_npm_lock("not json at all").is_err());
    }
}
